class TransientNetworkError(RuntimeError):
    """Raised when the API is unreachable due to a transient network condition.

    Treated as a non-failure by main(): logs and exits 0 without a desktop
    notification. Distinct from auth/format errors, which still notify.
    """


class AuthExpiredError(RuntimeError):
    """Raised when the Granola API token has expired (HTTP 401).

    This is a self-healing condition: the Granola desktop app refreshes the
    token whenever it's open. main() treats it as a non-failure (exit 0) but
    sends a single throttled notification so the user knows to open the app,
    rather than emitting a hard error every run.
    """


def _is_transient_network_error(exc):
    if isinstance(exc, (socket.timeout, ConnectionError, TimeoutError)):
        return True
    if isinstance(exc, urllib.error.URLError):
        reason = getattr(exc, "reason", exc)
        return isinstance(reason, (OSError, socket.timeout, socket.gaierror))
    return False

GRANOLA_CACHE_DIR = os.path.expanduser(
    "~/Library/Application Support/Granola"
)


def _find_latest_cache():
    """Find the highest-versioned cache-vN.json (or .json.enc) in Granola's data dir.

    Granola 7.220+ writes encrypted `cache-vN.json.enc` and leaves the plaintext
    `cache-vN.json` as a frozen stub. Prefer the freshest encrypted file when
    present, otherwise fall back to plaintext.
    """
    if not os.path.isdir(GRANOLA_CACHE_DIR):
        return os.path.join(GRANOLA_CACHE_DIR, "cache-v6.json")  # fallback
    candidates = []  # (version, mtime, filename)
    for f in os.listdir(GRANOLA_CACHE_DIR):
        m = re.match(r"^cache-v(\d+)\.json(\.enc)?$", f)
        if m:
            full = os.path.join(GRANOLA_CACHE_DIR, f)
            candidates.append((int(m.group(1)), os.path.getmtime(full), f))
    if not candidates:
        return os.path.join(GRANOLA_CACHE_DIR, "cache-v6.json")  # fallback
    candidates.sort(key=lambda c: (c[0], c[1]), reverse=True)
    return os.path.join(GRANOLA_CACHE_DIR, candidates[0][2])


_cached_dek = None


def _get_dek():
    """Return Granola's 32-byte data encryption key, or None if unavailable.

    The DEK is generated by the app, base64-encoded, then encrypted with
    Electron's `safeStorage.encryptString` (AES-128-CBC, IV=' '*16, key
    derived via PBKDF2 from the keychain entry `Granola Safe Storage`).
    """
    global _cached_dek
    if _cached_dek is not None:
        return _cached_dek
    dek_path = os.path.join(GRANOLA_CACHE_DIR, "storage.dek")
    if not os.path.exists(dek_path):
        return None
    try:
        # Pull keychain password (raw base64 string of the 16-byte AES seed).
        keychain_pw = subprocess.check_output(
            ["security", "find-generic-password",
             "-s", "Granola Safe Storage",
             "-a", "Granola Key", "-w"],
            stderr=subprocess.DEVNULL,
        ).decode().strip()
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        print(f"  Warning: could not read Granola keychain entry: {e}", file=sys.stderr)
        return None
    try:
        from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
        from cryptography.hazmat.primitives.padding import PKCS7
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM  # noqa: F401
    except ImportError:
        print("  Warning: `cryptography` package is required for Granola 7.220+", file=sys.stderr)
        return None

    # Decrypt storage.dek using standard Electron safeStorage scheme on macOS.
    blob = open(dek_path, "rb").read()
    if blob[:3] != b"v10":
        print(f"  Warning: storage.dek has unexpected prefix {blob[:3]!r}", file=sys.stderr)
        return None
    key = hashlib.pbkdf2_hmac("sha1", keychain_pw.encode(), b"saltysalt", 1003, dklen=16)
    cipher = Cipher(algorithms.AES(key), modes.CBC(b" " * 16)).decryptor()
    padded = cipher.update(blob[3:]) + cipher.finalize()
    unpad = PKCS7(128).unpadder()
    try:
        b64_dek = unpad.update(padded) + unpad.finalize()
        dek = base64.b64decode(b64_dek)
    except Exception as e:
        print(f"  Warning: failed to decrypt storage.dek: {e}", file=sys.stderr)
        return None
    if len(dek) != 32:
        print(f"  Warning: DEK has unexpected length {len(dek)}", file=sys.stderr)
        return None
    _cached_dek = dek
    return dek


def _decrypt_granola_file(path):
    """Decrypt a Granola `*.enc` file with the DEK. Returns bytes, or None on failure.

    File layout: [12-byte IV][ciphertext][16-byte GCM tag]. AES-256-GCM.
    """
    dek = _get_dek()
    if dek is None:
        return None
    try:
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    except ImportError:
        return None
    try:
        blob = open(path, "rb").read()
    except OSError as e:
        print(f"  Warning: could not read {path}: {e}", file=sys.stderr)
        return None
    if len(blob) < 12 + 16:
        return None
    iv, tag, ct = blob[:12], blob[-16:], blob[12:-16]
    try:
        return AESGCM(dek).decrypt(iv, ct + tag, None)
    except Exception as e:
        print(f"  Warning: AES-GCM decrypt failed for {os.path.basename(path)}: {e}", file=sys.stderr)
        return None


