def load_cache(cache_path):
    """Load and parse the Granola cache file (plaintext or encrypted)."""
    if cache_path.endswith(".enc"):
        plain = _decrypt_granola_file(cache_path)
        if plain is None:
            return {}
        raw = json.loads(plain.decode("utf-8"))
    else:
        with open(cache_path, "r") as f:
            raw = json.load(f)

    cache_data = raw["cache"]
    if isinstance(cache_data, str):
        cache_data = json.loads(cache_data)
    return cache_data["state"]


def load_api_token():
    """Load the Granola API access token from supabase.json (or .enc).

    Prefers the encrypted file when present and fresher than the plaintext
    one — Granola 7.220+ writes only to supabase.json.enc.
    """
    plain_path = os.path.join(GRANOLA_CACHE_DIR, "supabase.json")
    enc_path = plain_path + ".enc"
    data = None
    if os.path.exists(enc_path) and (
        not os.path.exists(plain_path)
        or os.path.getmtime(enc_path) > os.path.getmtime(plain_path)
    ):
        plain = _decrypt_granola_file(enc_path)
        if plain is not None:
            try:
                data = json.loads(plain.decode("utf-8"))
            except json.JSONDecodeError:
                data = None
    if data is None:
        try:
            with open(plain_path, "r") as f:
                data = json.load(f)
        except (OSError, json.JSONDecodeError):
            return None
    try:
        workos = data.get("workos_tokens")
        if isinstance(workos, str):
            workos = json.loads(workos)
        return workos.get("access_token") if workos else None
    except (json.JSONDecodeError, KeyError, AttributeError):
        return None


def _api_get_documents(token, doc_ids=None):
    """Fetch documents from the Granola API.

    If doc_ids is provided, fetches those specific documents.
    Otherwise fetches all documents.

    Returns the list of document dicts from the API.
    """
    payload_dict = {"include_last_viewed_panel": True}
    if doc_ids:
        payload_dict["filter_document_ids"] = doc_ids
    payload = json.dumps(payload_dict).encode("utf-8")

    req = urllib.request.Request(
        "https://api.granola.ai/v1/get-documents",
        data=payload,
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "Accept-Encoding": "gzip",
            "X-Client-Version": "7.220.0",
            "X-Granola-Platform": "darwin",
        },
        method="POST",
    )

    # Retry transient network errors — Mac may have just woken from sleep or
    # Wi-Fi may be reconnecting. Backoff: 2s, 8s, 20s.
    last_exc = None
    for attempt, delay in enumerate((2, 8, 20, None)):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                raw = resp.read()
                if resp.headers.get("Content-Encoding") == "gzip":
                    raw = gzip.decompress(raw)
                body = json.loads(raw)
            break
        except Exception as e:
            last_exc = e
            if not _is_transient_network_error(e) or delay is None:
                raise
            time.sleep(delay)
    else:
        raise last_exc

    # Handle API-level errors (e.g. {"message": "Unsupported client"})
    if isinstance(body, dict) and "message" in body and "docs" not in body:
        raise RuntimeError(f"API returned error: {body['message']}")

    return body.get("docs", body) if isinstance(body, dict) else body


def fetch_api_documents(token):
    """Fetch all documents from the Granola API.

    Returns a tuple (documents_dict, api_panels_dict, transient_failure,
    auth_expired) where:
    - documents_dict maps doc_id -> document dict (matching cache format)
    - api_panels_dict maps doc_id -> Tiptap content dict
    - transient_failure is True iff the fetch failed for a transient network reason
    - auth_expired is True iff the API rejected the token with HTTP 401
    """
    documents = {}
    api_panels = {}
    transient_failure = False
    auth_expired = False

    try:
        docs = _api_get_documents(token)
        for doc in docs:
            doc_id = doc.get("id")
            if not doc_id:
                continue
            documents[doc_id] = doc
            panel = doc.get("last_viewed_panel")
            if panel and panel.get("content"):
                api_panels[doc_id] = panel["content"]
    except Exception as e:
        print(f"  Warning: API fetch failed: {e}", file=sys.stderr)
        if isinstance(e, urllib.error.HTTPError) and e.code == 401:
            auth_expired = True
        elif _is_transient_network_error(e):
            transient_failure = True

    return documents, api_panels, transient_failure, auth_expired


def fetch_api_panels(token, doc_ids):
    """Fetch summary panels from the Granola API.

    Returns a dict mapping doc_id -> Tiptap content dict.
    Returns an empty dict on any error.
    """
    if not doc_ids:
        return {}

    result = {}
    batch_size = 100

    for i in range(0, len(doc_ids), batch_size):
        batch = doc_ids[i : i + batch_size]
        try:
            docs = _api_get_documents(token, doc_ids=batch)
            for doc in docs:
                panel = doc.get("last_viewed_panel")
                if panel and panel.get("content"):
                    result[doc["id"]] = panel["content"]
        except Exception:
            continue

    return result


def load_sync_state(output_dir):
    """Load the sync state tracking file."""
    state_path = os.path.join(output_dir, STATE_FILE)
    if os.path.exists(state_path):
        with open(state_path, "r") as f:
            return json.load(f)
    return {}


def save_sync_state(output_dir, state):
    """Save the sync state tracking file."""
    state_path = os.path.join(output_dir, STATE_FILE)
    with open(state_path, "w") as f:
        json.dump(state, f, indent=2)


def sync(cache_path, output_dir, force=False, dry_run=False, verbose=False, no_api=False):
    """Main sync function."""
    log = lambda msg: print(msg) if verbose else None

    log(f"Loading cache from {cache_path}")
    state = load_cache(cache_path)

    documents = state.get("documents", {})
    panels = state.get("documentPanels", {})
    transcripts = state.get("transcripts", {})

    # Fetch documents and panels from API to supplement the cache
    api_panels = {}
    api_transient_failure = False
    api_auth_expired = False
    if not no_api:
        token = load_api_token()
        if token:
            log("Fetching documents from API...")
            api_documents, api_panels, api_transient_failure, api_auth_expired = (
                fetch_api_documents(token)
            )
            # Merge API documents into cache (API wins for existing, adds missing)
            new_from_api = 0
            for doc_id, doc in api_documents.items():
                if doc_id not in documents:
                    new_from_api += 1
                documents[doc_id] = doc
            log(f"  API returned {len(api_documents)} documents ({new_from_api} new beyond cache)")
            log(f"  Fetched {len(api_panels)} panels from API")

            # Also fetch panels for any cache-only docs missing panels
            if not panels:
                cache_only = [d for d in documents if d not in api_panels and not documents[d].get("deleted_at")]
                if cache_only:
                    extra = fetch_api_panels(token, cache_only)
                    api_panels.update(extra)
                    log(f"  Fetched {len(extra)} additional panels for cache-only docs")
        else:
            log("No API token found, skipping API fetch")

    # Build reverse lookup: document_id -> [folder_name, ...]
    doc_lists_meta = state.get("documentListsMetadata", {})
    doc_lists = state.get("documentLists", {})
    doc_folders = {}
    for list_id, doc_ids in doc_lists.items():
        name = doc_lists_meta.get(list_id, {}).get("title")
        if name:
            for did in doc_ids:
                doc_folders.setdefault(did, []).append(name)
    for did in doc_folders:
        doc_folders[did].sort()

    log(f"Found {len(documents)} documents, {len(transcripts)} transcripts")

    os.makedirs(output_dir, exist_ok=True)
    sync_state = load_sync_state(output_dir) if not force else {}

    # Safety guard: if we loaded zero documents but previously synced many, something
    # went wrong (stale cache, API auth failure, format change). Abort rather than
    # deleting every existing file as "orphans". Falls back to counting .md files on
    # disk so the guard still fires if the sync-state file was wiped.
    _prior_doc_count = sum(1 for v in sync_state.values() if v.get("filename"))
    if _prior_doc_count == 0:
        try:
            _prior_doc_count = sum(
                1 for f in os.listdir(output_dir)
                if f.endswith(".md") and not f.endswith("_transcript.md")
            )
        except OSError:
            pass
    if len(documents) == 0 and _prior_doc_count > 5:
        if api_auth_expired:
            raise AuthExpiredError(
                "Granola API token expired — open the Granola app to refresh it. "
                f"Skipping this run ({_prior_doc_count} notes preserved on disk)."
            )
        if api_transient_failure:
            raise TransientNetworkError(
                f"API unreachable; cache produced 0 docs ({_prior_doc_count} on disk). "
                "Skipping this run."
            )
        raise RuntimeError(
            f"Loaded 0 documents but sync state tracks {_prior_doc_count} files. "
            "Cache may be stale or API auth expired. Run with --no-api to use cache "
            "only, or --force to override this check."
        )

    # First pass: determine all filenames to detect collisions
    all_data = {}
    filenames_used = set()
    for doc_id, doc in documents.items():
        if doc.get("deleted_at") or doc.get("was_trashed"):
            log(f"  Skipping deleted: {doc.get('title', doc_id)}")
            continue
        data = extract_meeting_data(
            doc, panels,
            folders=doc_folders.get(doc_id),
            api_panel=api_panels.get(doc_id),
        )
        all_data[doc_id] = data

    # Assign filenames (detect collisions)
    filenames = {}
    filename_counts = {}
    for doc_id, data in all_data.items():
        slug = slugify(data["title"]) or "untitled"
        base = f"{data['date']}_{slug}"
        filename = f"{base}.md"
        if filename in filename_counts:
            filename_counts[filename] += 1
            filename = f"{base}_{doc_id[:8]}.md"
        else:
            filename_counts[filename] = 1
        filenames[doc_id] = filename

    # Handle collisions for the first occurrence too
    for doc_id, data in all_data.items():
        slug = slugify(data["title"]) or "untitled"
        base = f"{data['date']}_{slug}"
        orig_filename = f"{base}.md"
        if filename_counts.get(orig_filename, 0) > 1 and filenames[doc_id] == orig_filename:
            filenames[doc_id] = f"{base}_{doc_id[:8]}.md"

    # Sync each document
    created = 0
    updated = 0
    skipped = 0
    new_sync_state = {}

    for doc_id, data in all_data.items():
        filename = filenames[doc_id]
        prev = sync_state.get(doc_id, {})

        # Check if update needed
        if not force and prev.get("updated_at") == data["updated_at"]:
            new_sync_state[doc_id] = prev
            skipped += 1
            continue

        # Clean up old file if title/date changed (rename detection)
        old_filename = prev.get("filename")
        if old_filename and old_filename != filename:
            old_path = os.path.join(output_dir, old_filename)
            if os.path.exists(old_path):
                if dry_run:
                    log(f"  Would remove old file: {old_filename}")
                else:
                    os.remove(old_path)
                    log(f"  Removed old file: {old_filename}")

        # Write the file
        filepath = os.path.join(output_dir, filename)
        content = build_markdown(data)

        if dry_run:
            action = "create" if not prev else "update"
            log(f"  Would {action}: {filename}")
        else:
            with open(filepath, "w") as f:
                f.write(content)
            if prev:
                updated += 1
                log(f"  Updated: {filename}")
            else:
                created += 1
                log(f"  Created: {filename}")

        new_sync_state[doc_id] = {
            "updated_at": data["updated_at"],
            "filename": filename,
        }

    # Export transcripts (ephemeral in cache — save before Granola evicts them)
    transcripts_saved = 0
    for doc_id, utterances in transcripts.items():
        if not utterances or doc_id not in all_data:
            continue
        prev = new_sync_state.get(doc_id, sync_state.get(doc_id, {}))
        if prev.get("transcript_saved"):
            continue  # Already captured this transcript

        data = all_data[doc_id]
        slug = slugify(data["title"]) or "untitled"
        transcript_filename = f"{data['date']}_{slug}_transcript.md"
        transcript_path = os.path.join(output_dir, transcript_filename)
        transcript_md = format_transcript(utterances)

        if dry_run:
            log(f"  Would save transcript: {transcript_filename} ({len(utterances)} utterances)")
        else:
            with open(transcript_path, "w") as f:
                f.write(f"---\ntitle: \"{data['title']} — Transcript\"\n")
                f.write(f"date: {data['date']}\n")
                f.write(f"granola_id: {doc_id}\n")
                f.write(f"type: transcript\n---\n\n")
                f.write(f"# {data['title']} — Transcript\n\n")
                f.write(transcript_md)
                f.write("\n")
            log(f"  Saved transcript: {transcript_filename} ({len(utterances)} utterances)")

        transcripts_saved += 1
        if doc_id in new_sync_state:
            new_sync_state[doc_id]["transcript_saved"] = True
            new_sync_state[doc_id]["transcript_filename"] = transcript_filename
        else:
            new_sync_state[doc_id] = {
                "updated_at": data["updated_at"],
                "filename": filenames.get(doc_id, ""),
                "transcript_saved": True,
                "transcript_filename": transcript_filename,
            }

    # Clean up files for documents no longer in cache
    # Note: transcript files are preserved even if the document leaves the cache
    orphans = []
    for doc_id, prev in sync_state.items():
        if doc_id not in all_data:
            prev_filename = prev.get("filename", "")
            if prev_filename:
                old_path = os.path.join(output_dir, prev_filename)
                if os.path.exists(old_path):
                    orphans.append((doc_id, prev_filename, old_path))
            # Preserve transcript state so the file isn't orphaned
            if prev.get("transcript_saved"):
                new_sync_state[doc_id] = {
                    "transcript_saved": True,
                    "transcript_filename": prev["transcript_filename"],
                }

    # Safety bound: a sudden mass-orphan is almost always a bug (schema change,
    # partial API response, auth scope shrink). Refuse rather than delete in bulk.
    prior_tracked = sum(1 for v in sync_state.values() if v.get("filename"))
    if (
        not dry_run
        and prior_tracked > 10
        and len(orphans) / prior_tracked > ORPHAN_REMOVAL_MAX_FRACTION
    ):
        raise RuntimeError(
            f"Refusing to remove {len(orphans)} of {prior_tracked} tracked files "
            f"(> {ORPHAN_REMOVAL_MAX_FRACTION:.0%}). This usually indicates a "
            "schema or API change. Inspect the orphan list above, then either "
            "remove the obsolete files manually or delete the corresponding "
            "entries from .sync-state.json before re-running."
        )

    removed = 0
    for _doc_id, prev_filename, old_path in orphans:
        if dry_run:
            log(f"  Would remove orphan: {prev_filename}")
        else:
            os.remove(old_path)
            log(f"  Removed orphan: {prev_filename}")
        removed += 1

    if not dry_run:
        save_sync_state(output_dir, new_sync_state)

    prefix = "[DRY RUN] " if dry_run else ""
    parts = [
        f"{created} created, {updated} updated",
        f"{skipped} unchanged, {removed} removed",
    ]
    if transcripts_saved:
        parts.append(f"{transcripts_saved} transcripts saved")
    print(f"{prefix}Sync complete: {', '.join(parts)}")


